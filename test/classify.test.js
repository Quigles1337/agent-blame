// --- built-in agents: author form -------------------------------------------

test('agent as author: claude, copilot-swe-agent[bot], cursor, codex', () => {
  const claude = classify(authoredBy('Claude', 'noreply@anthropic.com'));
  assert.equal(claude.kind, 'agent');
  assert.equal(claude.authorKind, 'agent');
  assert.equal(claude.assisted, false);
  assert.equal(claude.evidence[0].source, 'author');

  const copilot = classify(authoredBy('copilot-swe-agent[bot]', '198982749+Copilot@users.noreply.github.com'));
  assert.deepEqual(copilot.agents, ['copilot']);
  assert.equal(copilot.kind, 'agent', '[bot] suffix must not demote a listed agent to bot');

  assert.deepEqual(classify(authoredBy('Cursor Agent', 'cursoragent@cursor.com')).agents, ['cursor']);
  assert.deepEqual(classify(authoredBy('OpenAI Codex', 'codex@openai.com')).agents, ['codex']);
});

test('agent as committer only is still agent evidence', () => {
  const r = classify(commit({ committerName: 'Claude', committerEmail: 'noreply@anthropic.com' }));
  assert.equal(r.kind, 'agent');
  assert.equal(r.evidence[0].source, 'committer');
  assert.equal(r.authorKind, 'human');
});

// --- bots -----------------------------------------------------------------

test('non-AI bots are classified bot: dependabot, renovate, github-actions, arbitrary [bot]', () => {
  for (const [name, email] of [
    ['dependabot[bot]', '49699333+dependabot[bot]@users.noreply.github.com'],
    ['renovate[bot]', '29139614+renovate[bot]@users.noreply.github.com'],
    ['github-actions[bot]', '41898282+github-actions[bot]@users.noreply.github.com'],
    ['github-actions', 'github-actions@github.com'],
    ['some-company-automation[bot]', 'x@example.com'],
  ]) {
    const r = classify(authoredBy(name, email));
    assert.equal(r.kind, 'bot', `${name} should be bot`);
    assert.deepEqual(r.agents, []);
    assert.equal(r.authorKind, 'bot');
  }
});

test('precedence: agent evidence wins over a bot author', () => {
  const r = classify({
    ...authoredBy('github-actions[bot]', '41898282+github-actions[bot]@users.noreply.github.com'),
    trailers: [{ key: 'Co-authored-by', value: 'Claude <noreply@anthropic.com>' }],
  });
  assert.equal(r.kind, 'agent');
  assert.deepEqual(r.agents, ['claude']);
  assert.equal(r.authorKind, 'bot');
});

test('a bot committer does not make a human commit a bot', () => {
  const r = classify(commit({ committerName: 'github-actions[bot]', committerEmail: '41898282+github-actions[bot]@users.noreply.github.com' }));
  assert.equal(r.kind, 'human');
});

// --- mixed ---------------------------------------------------------------

test('human author + agent trailer is agent, assisted, with the human still the author', () => {
  const r = classify(withTrailer('Claude <noreply@anthropic.com>'));
  assert.equal(r.kind, 'agent');
  assert.equal(r.authorKind, 'human');
  assert.equal(r.assisted, true);
});

test('multiple agents on one commit are all reported, in canonical order, without duplicates', () => {
  const r = classify(commit({
    trailers: [
      { key: 'Co-authored-by', value: 'Copilot <copilot@users.noreply.github.com>' },
      { key: 'Co-authored-by', value: 'Claude <noreply@anthropic.com>' },
      { key: 'Co-authored-by', value: 'Claude <noreply@anthropic.com>' },
    ],
  }));
  assert.deepEqual(r.agents, ['claude', 'copilot']);
  assert.equal(r.evidence.length, 2);
});

test('trailer key matching is case-insensitive and ignores unrelated trailers', () => {
  const r = classify(commit({ trailers: [
    { key: 'Reviewed-by', value: 'Claude <noreply@anthropic.com>' },
    { key: 'co-authored-by', value: 'Claude <noreply@anthropic.com>' },
  ] }));
  assert.equal(r.evidence.length, 1);
  assert.equal(r.evidence[0].value, 'co-authored-by: Claude <noreply@anthropic.com>');
});

// --- configuration ----------------------------------------------------------

test('config adds a custom agent that extends the built-ins', () => {
  const cls = createClassifier({ config: { agents: { 'my-internal-bot': { label: 'Internal', emails: ['bot@corp.example'], names: ['/^corp-?bot/'], markers: ['[auto-generated]'] } } } });
  assert.deepEqual(cls(withTrailer('CorpBot <bot@corp.example>')).agents, ['my-internal-bot']);
  assert.deepEqual(cls(authoredBy('corp-bot', 'someone@corp.example')).agents, ['my-internal-bot']);
  assert.deepEqual(cls(commit({ body: 'Summary [auto-generated] by the pipeline' })).agents, ['my-internal-bot']);
  assert.deepEqual(cls(withTrailer('Claude <noreply@anthropic.com>')).agents, ['claude']);
  assert.equal(cls.labels['my-internal-bot'], 'Internal');
});

test('config can extend or disable a built-in agent', () => {
  const extended = createClassifier({ config: { agents: { claude: { emails: ['claude@corp.example'] } } } });
  assert.deepEqual(extended(withTrailer('Assistant <claude@corp.example>')).agents, ['claude']);
  assert.equal(extended.labels.claude, 'Claude Code');

  const disabled = createClassifier({ config: { agents: { copilot: false } } });
  assert.equal(disabled(withTrailer('Copilot <copilot@users.noreply.github.com>')).kind, 'human');
  assert.deepEqual(disabled(withTrailer('Claude <noreply@anthropic.com>')).agents, ['claude']);
});

test('defaultPatterns: false uses the config only', () => {
  const cls = createClassifier({ defaultPatterns: false, config: { agents: { mine: { emails: ['bot@corp.example'] } } } });
  assert.equal(cls(withTrailer('Claude <noreply@anthropic.com>')).kind, 'human');
  assert.deepEqual(cls(withTrailer('X <bot@corp.example>')).agents, ['mine']);
  assert.equal(cls(authoredBy('dependabot[bot]', 'x@y')).kind, 'human', 'default bot patterns are off too');
  assert.equal(cls(withTrailer('Tool', 'Assisted-by')).kind, 'human', 'no other-agent bucket without defaults');
});

test('config bots extend the bot list', () => {
  const cls = createClassifier({ config: { bots: { names: ['/^ci-deployer$/'], emails: ['deploy@corp.example'] } } });
  assert.equal(cls(authoredBy('ci-deployer', 'x@corp.example')).kind, 'bot');
  assert.equal(cls(authoredBy('Someone', 'deploy@corp.example')).kind, 'bot');
});

test('AGENT_IDS is the canonical ordering and every built-in id is present on the default classifier', () => {
  const cls = createClassifier();
  for (const id of AGENT_IDS) assert.ok(cls.agents.has(id), id);
  assert.equal(AGENT_IDS[0], 'claude');
  assert.equal(AGENT_IDS.at(-1), 'other-agent');
});
