/** Trailer keys that are themselves a declaration of AI assistance. */
const AI_TRAILER_KEYS = new Set(['assisted-by', 'ai-assisted-by', 'generated-by', 'ai-generated-by', 'ai-agent']);
/** Trailer keys that name a co-author (which may or may not be an agent). */
const COAUTHOR_TRAILER_KEYS = new Set(['co-authored-by']);

const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Turn a user-supplied pattern into a RegExp.
 *  - `/body/flags` is a regular expression (the `i` flag is always added).
 *  - any other string is a case-insensitive literal: whole-string for
 *    identities, substring for markers.
 */
export function compilePattern(input, mode = 'identity') {
  if (input instanceof RegExp) {
    return input.flags.includes('i') ? input : new RegExp(input.source, input.flags + 'i');
  }
  if (typeof input !== 'string' || input.length === 0) {
    throw new TypeError(`Pattern must be a non-empty string or RegExp, got ${JSON.stringify(input)}`);
  }
  const m = /^\/(.+)\/([a-z]*)$/s.exec(input);
  if (m) {
    const flags = m[2].includes('i') ? m[2] : m[2] + 'i';
    return new RegExp(m[1], flags);
  }
  const body = escapeRegExp(input);
  return mode === 'marker' ? new RegExp(body, 'i') : new RegExp(`^${body}$`, 'i');
}

function compileAgent(id, def, base) {
  if (def === false || def === null) return null;
  if (typeof def !== 'object' || Array.isArray(def)) {
    throw new TypeError(`agents.${id} must be an object or false`);
  }
  const list = (k, mode) => {
    const v = def[k] ?? [];
    if (!Array.isArray(v)) throw new TypeError(`agents.${id}.${k} must be an array`);
    return v.map((p) => compilePattern(p, mode));
  };
  const pairs = (def.pairs ?? []).map((p) => ({
    name: compilePattern(p.name, 'identity'),
    email: compilePattern(p.email, 'identity'),
  }));
  return {
    label: def.label ?? base?.label ?? id,
    emails: [...(base?.emails ?? []), ...list('emails', 'identity')],
    names: [...(base?.names ?? []), ...list('names', 'identity')],
    pairs: [...(base?.pairs ?? []), ...pairs],
    markers: [...(base?.markers ?? []), ...list('markers', 'marker')],
  };
}

/**
 * Build a classifier from the built-in patterns plus an optional user config
 * (`.agent-blame.json`). With `defaultPatterns: false` only the config is used.
 *
 * The returned function has two extra properties: `agents` (a Map of id to
 * compiled definition) and `labels` (id to display label).
 */
export function createClassifier({ config = {}, defaultPatterns = true } = {}) {
  const agents = new Map();
  if (defaultPatterns) {
    for (const id of AGENT_IDS) agents.set(id, { ...DEFAULT_AGENTS[id] });
  }
  for (const [id, def] of Object.entries(config.agents ?? {})) {
    const compiled = compileAgent(id, def, agents.get(id));
    if (compiled === null) agents.delete(id);
    else agents.set(id, compiled);
  }

  const bots = {
    names: [
      ...(defaultPatterns ? DEFAULT_BOTS.names : []),
      ...(config.bots?.names ?? []).map((p) => compilePattern(p)),
    ],
    emails: [
      ...(defaultPatterns ? DEFAULT_BOTS.emails : []),
      ...(config.bots?.emails ?? []).map((p) => compilePattern(p)),
    ],
  };

  const agentList = [...agents.entries()];

  function matchIdentity(name, email) {
    const n = (name ?? '').trim();
    const e = (email ?? '').trim();
    for (const [id, def] of agentList) {
      for (const re of def.emails) if (e && re.test(e)) return { agent: id, via: 'email' };
      for (const re of def.names) if (n && re.test(n)) return { agent: id, via: 'name' };
      for (const pair of def.pairs) {
        if (n && e && pair.name.test(n) && pair.email.test(e)) return { agent: id, via: 'name+email' };
      }
    }
    return null;
  }

  function isBot(name, email) {
    const n = (name ?? '').trim();
    const e = (email ?? '').trim();
    return bots.names.some((re) => n && re.test(n)) || bots.emails.some((re) => e && re.test(e));
  }

  function classify(commit) {
    const evidence = [];
    const seen = new Set();
    const add = (agent, source, value) => {
      const key = `${agent}\0${source}\0${value}`;
      if (seen.has(key)) return;
      seen.add(key);
      evidence.push({ agent, source, value });
    };

    const authorMatch = matchIdentity(commit.authorName, commit.authorEmail);
    if (authorMatch) add(authorMatch.agent, 'author', formatIdentity(commit.authorName, commit.authorEmail));

    const committerMatch = matchIdentity(commit.committerName, commit.committerEmail);
    if (committerMatch) {
      add(committerMatch.agent, 'committer', formatIdentity(commit.committerName, commit.committerEmail));
    }

    for (const trailer of commit.trailers ?? []) {
      const key = String(trailer.key ?? '').toLowerCase();
      if (!COAUTHOR_TRAILER_KEYS.has(key) && !AI_TRAILER_KEYS.has(key)) continue;
      const { name, email } = parseIdentity(trailer.value);
      const match = matchIdentity(name, email);
      if (match) add(match.agent, 'trailer', `${trailer.key}: ${trailer.value}`);
      else if (AI_TRAILER_KEYS.has(key) && agents.has('other-agent')) {
        add('other-agent', 'trailer', `${trailer.key}: ${trailer.value}`);
      }
    }

    const message = `${commit.subject ?? ''}\n${commit.body ?? ''}`;
    for (const [id, def] of agentList) {
      for (const re of def.markers) {
        const m = re.exec(message);
        if (m) add(id, 'message', m[0].trim());
      }
    }

    const agentsFound = AGENT_IDS.filter((id) => evidence.some((ev) => ev.agent === id));
    for (const ev of evidence) if (!agentsFound.includes(ev.agent)) agentsFound.push(ev.agent);

    const authorIsBot = isBot(commit.authorName, commit.authorEmail);
    const authorKind = authorMatch ? 'agent' : authorIsBot ? 'bot' : 'human';

    let kind;
    if (evidence.length > 0) kind = 'agent';
    else if (authorIsBot) kind = 'bot';
    else kind = 'human';

    return {
      kind,
      agents: agentsFound,
      evidence,
      authorKind,
      assisted: kind === 'agent' && authorKind === 'human',
    };
  }

  classify.agents = agents;
  classify.labels = Object.fromEntries(agentList.map(([id, def]) => [id, def.label]));
  return classify;
}

/** Parse `Name <email>` (either part may be missing). */
export function parseIdentity(value) {
  const v = String(value ?? '').trim();
  const m = /^(.*?)\s*<([^<>]*)>\s*$/.exec(v);
  if (m) return { name: m[1].trim(), email: m[2].trim() };
  if (/^[^\s<>@]+@[^\s<>@]+$/.test(v)) return { name: '', email: v };
  return { name: v, email: '' };
}

function formatIdentity(name, email) {
  const n = (name ?? '').trim();
  const e = (email ?? '').trim();
  if (n && e) return `${n} <${e}>`;
  return n || e;
}

/** Parse the output of `%(trailers:only,unfold)` into `{key, value}` pairs. */
export function parseTrailers(text) {
  const out = [];
  for (const raw of String(text ?? '').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    const m = /^([A-Za-z][A-Za-z0-9-]*)\s*:\s*(.*)$/.exec(line);
    if (m) out.push({ key: m[1], value: m[2].trim() });
  }
  return out;
}

const defaultClassifier = createClassifier();

/** Classify with the built-in patterns only. */
export function classify(commit) {
  return defaultClassifier(commit);
}
